export function exportFactLabel(key: string): string {
  return LABELS[key] ?? key.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (first) => first.toUpperCase());
}

export function exportFactValue(key: string, value: unknown): string {
  if (value === null || value === undefined) return 'Unavailable';
  if (typeof value === 'boolean') return value ? 'Yes' : 'No';
  if (typeof value === 'number') {
    if (['capturedAt', 'startedAt', 'endedAt', 'at'].includes(key))
      return `${new Date(value).toLocaleString()} (${value} milliseconds since 1970-01-01 UTC)`;
    if (key === 'durationMs' || key === 'milliseconds') return `${formatDuration(value)} (${value} ms)`;
    if (key === 'dollars' || key === 'recordedCost') return `${formatCost(value) ?? '$0.00'} (${value} USD)`;
    if (key === 'tokens' && value >= 10_000) return `${formatTokens(value)} (${value.toLocaleString('en-US')} tokens)`;
    return value.toLocaleString('en-US', { maximumSignificantDigits: 21 });
  }
  const classification = [
    'deliberatelyOmitted',
    'kind',
    'ownership',
    'reason',
    'role',
    'origin',
    'inferenceClass',
    'contextBand',
    'usage',
    'cost',
    'text',
    'relationships',
    'inventory',
    'context',
    'changes',
  ].includes(key);
  return typeof value === 'string' ? (classification ? (VALUES[value] ?? value) : value) : String(value);
}
